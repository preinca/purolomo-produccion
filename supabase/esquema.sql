-- Esquema de la base de datos de Purolomo Producción en Supabase (Postgres).
-- Se aplica con `npm run db:migrar` y se puede volver a ejecutar sin perder datos.
-- Las fechas se guardan como texto ISO (igual que en la versión SQLite) para no cambiar la aplicación.

CREATE TABLE IF NOT EXISTS productos (
  codigo TEXT PRIMARY KEY,
  nombre TEXT NOT NULL,
  tipo TEXT NOT NULL,
  descripcion TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS lotes (
  tag TEXT PRIMARY KEY,
  fecha TEXT NOT NULL,
  semana TEXT NOT NULL,
  codigo TEXT NOT NULL,
  producto TEXT NOT NULL,
  kg_recibidos DOUBLE PRECISION NOT NULL DEFAULT 0 CHECK (kg_recibidos >= 0),
  kg_despachados DOUBLE PRECISION NOT NULL DEFAULT 0 CHECK (kg_despachados >= 0),
  kg_consumidos DOUBLE PRECISION NOT NULL DEFAULT 0 CHECK (kg_consumidos >= 0),
  estado TEXT NOT NULL,
  observaciones TEXT NOT NULL DEFAULT '',
  destino TEXT NOT NULL DEFAULT '',
  creado_en TEXT NOT NULL DEFAULT to_char(clock_timestamp() AT TIME ZONE 'UTC', 'YYYY-MM-DD"T"HH24:MI:SS.MS"Z"')
);

CREATE TABLE IF NOT EXISTS movimientos (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tag TEXT NOT NULL,
  tipo TEXT NOT NULL CHECK (tipo IN ('recepcion', 'despacho', 'consumo', 'devolucion', 'transferencia')),
  fecha TEXT NOT NULL,
  semana TEXT NOT NULL,
  kg DOUBLE PRECISION NOT NULL CHECK (kg >= 0),
  estado TEXT NOT NULL,
  nota TEXT NOT NULL DEFAULT '',
  destino TEXT NOT NULL DEFAULT '',
  linea TEXT NOT NULL DEFAULT '',
  creado_en TEXT NOT NULL DEFAULT to_char(clock_timestamp() AT TIME ZONE 'UTC', 'YYYY-MM-DD"T"HH24:MI:SS.MS"Z"')
);

CREATE INDEX IF NOT EXISTS idx_lotes_fecha ON lotes (fecha DESC, tag DESC);
CREATE INDEX IF NOT EXISTS idx_lotes_estado ON lotes (estado, fecha DESC);
CREATE INDEX IF NOT EXISTS idx_lotes_codigo ON lotes (codigo);
CREATE INDEX IF NOT EXISTS idx_lotes_creado ON lotes (creado_en DESC, tag DESC);
CREATE INDEX IF NOT EXISTS idx_mov_tag ON movimientos (tag, id DESC);
CREATE INDEX IF NOT EXISTS idx_mov_tipo ON movimientos (tipo, fecha DESC);

CREATE TABLE IF NOT EXISTS recetas (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  destino TEXT NOT NULL,
  linea TEXT NOT NULL DEFAULT '1',
  objetivo_kg DOUBLE PRECISION NOT NULL,
  tolerancia_kg DOUBLE PRECISION NOT NULL,
  minimo_kg DOUBLE PRECISION,
  maximo_kg DOUBLE PRECISION,
  creado_en TEXT NOT NULL DEFAULT to_char(clock_timestamp() AT TIME ZONE 'UTC', 'YYYY-MM-DD"T"HH24:MI:SS.MS"Z"')
);

CREATE TABLE IF NOT EXISTS receta_items (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  receta_id INTEGER NOT NULL,
  tipo TEXT NOT NULL,
  kg DOUBLE PRECISION NOT NULL CHECK (kg > 0),
  tolerancia_kg DOUBLE PRECISION NOT NULL DEFAULT 15,
  minimo_kg DOUBLE PRECISION,
  maximo_kg DOUBLE PRECISION,
  UNIQUE (receta_id, tipo)
);

CREATE TABLE IF NOT EXISTS pesajes (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  numero INTEGER NOT NULL,
  fecha TEXT NOT NULL,
  destino TEXT NOT NULL,
  linea TEXT NOT NULL,
  receta_id INTEGER NOT NULL,
  observaciones TEXT NOT NULL DEFAULT '',
  finalizado INTEGER NOT NULL DEFAULT 0,
  registrado_en TEXT NOT NULL DEFAULT '',
  creado_en TEXT NOT NULL DEFAULT to_char(clock_timestamp() AT TIME ZONE 'UTC', 'YYYY-MM-DD"T"HH24:MI:SS.MS"Z"'),
  UNIQUE (fecha, destino, linea, numero)
);

CREATE INDEX IF NOT EXISTS idx_pesajes_destino ON pesajes (destino, fecha DESC, numero DESC);

CREATE TABLE IF NOT EXISTS minilotes (
  token TEXT PRIMARY KEY,
  tag TEXT NOT NULL,
  pesaje_id INTEGER NOT NULL,
  tipo TEXT NOT NULL,
  kg DOUBLE PRECISION NOT NULL CHECK (kg > 0),
  destino TEXT NOT NULL,
  linea TEXT NOT NULL,
  creado_en TEXT NOT NULL DEFAULT to_char(clock_timestamp() AT TIME ZONE 'UTC', 'YYYY-MM-DD"T"HH24:MI:SS.MS"Z"')
);

CREATE INDEX IF NOT EXISTS idx_mini_pesaje ON minilotes (pesaje_id, tipo, creado_en);
CREATE INDEX IF NOT EXISTS idx_mini_tag ON minilotes (tag);

CREATE TABLE IF NOT EXISTS usuarios (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre TEXT NOT NULL,
  usuario TEXT NOT NULL,
  clave TEXT NOT NULL,
  rango TEXT NOT NULL CHECK (rango IN ('administrador', 'consulta', 'recepcionista', 'pesador')),
  activo INTEGER NOT NULL DEFAULT 1,
  creado_en TEXT NOT NULL DEFAULT to_char(clock_timestamp() AT TIME ZONE 'UTC', 'YYYY-MM-DD"T"HH24:MI:SS.MS"Z"')
);

CREATE UNIQUE INDEX IF NOT EXISTS idx_usuarios_usuario ON usuarios (lower(usuario));

CREATE TABLE IF NOT EXISTS app_meta (
  clave TEXT PRIMARY KEY,
  valor TEXT NOT NULL
);

ALTER TABLE lotes ADD COLUMN IF NOT EXISTS impresa_en TEXT NOT NULL DEFAULT '';

CREATE TABLE IF NOT EXISTS impresiones (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  estado TEXT NOT NULL DEFAULT 'pendiente',
  creada_en TEXT NOT NULL DEFAULT to_char(clock_timestamp() AT TIME ZONE 'UTC', 'YYYY-MM-DD"T"HH24:MI:SS.MS"Z"'),
  tomada_en TEXT NOT NULL DEFAULT '',
  lista_en TEXT NOT NULL DEFAULT ''
);

CREATE TABLE IF NOT EXISTS impresion_items (
  impresion_id INTEGER NOT NULL,
  tag TEXT NOT NULL,
  orden INTEGER NOT NULL
);

-- La aplicación entra con la conexión directa a Postgres, que no pasa por RLS.
-- Activar RLS sin políticas cierra estas tablas a la API pública de Supabase (clave anon).
ALTER TABLE productos ENABLE ROW LEVEL SECURITY;
ALTER TABLE lotes ENABLE ROW LEVEL SECURITY;
ALTER TABLE movimientos ENABLE ROW LEVEL SECURITY;
ALTER TABLE recetas ENABLE ROW LEVEL SECURITY;
ALTER TABLE receta_items ENABLE ROW LEVEL SECURITY;
ALTER TABLE pesajes ENABLE ROW LEVEL SECURITY;
ALTER TABLE minilotes ENABLE ROW LEVEL SECURITY;
ALTER TABLE usuarios ENABLE ROW LEVEL SECURITY;
ALTER TABLE app_meta ENABLE ROW LEVEL SECURITY;
ALTER TABLE impresiones ENABLE ROW LEVEL SECURITY;
ALTER TABLE impresion_items ENABLE ROW LEVEL SECURITY;
