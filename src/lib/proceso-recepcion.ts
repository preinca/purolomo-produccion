import type { Db } from "./db";
import type { Resultado } from "./lotes";

const esquemaGlobal = globalThis as { purolomoProceso?: Promise<void> };

export type ProcesoAbierto = {
  id: number;
  entradas: number;
};

export type ProcesoPorImprimir = {
  id: number;
  entradas: number;
};

export function asegurarProceso(db: Db) {
  if (!esquemaGlobal.purolomoProceso) {
    esquemaGlobal.purolomoProceso = prepararProceso(db).catch((error: unknown) => {
      esquemaGlobal.purolomoProceso = undefined;
      throw error;
    });
  }
  return esquemaGlobal.purolomoProceso;
}

async function prepararProceso(db: Db) {
  try {
    await db.get("SELECT proceso_id, impresa_en FROM lotes LIMIT 1");
    await db.get("SELECT id FROM procesos_recepcion LIMIT 1");
  } catch {
    await db.exec(`
      ALTER TABLE lotes ADD COLUMN IF NOT EXISTS impresa_en TEXT NOT NULL DEFAULT '';
      ALTER TABLE lotes ADD COLUMN IF NOT EXISTS proceso_id INTEGER NOT NULL DEFAULT 0;
      CREATE TABLE IF NOT EXISTS procesos_recepcion (
        id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        estado TEXT NOT NULL DEFAULT 'abierta',
        iniciada_en TEXT NOT NULL DEFAULT to_char(clock_timestamp() AT TIME ZONE 'UTC', 'YYYY-MM-DD"T"HH24:MI:SS.MS"Z"'),
        cerrada_en TEXT NOT NULL DEFAULT ''
      );
    `);
  }
}

export async function procesoAbierto(db: Db): Promise<ProcesoAbierto | null> {
  await asegurarProceso(db);
  const fila = await db.get<{ id: number }>(
    "SELECT id FROM procesos_recepcion WHERE estado = 'abierta' ORDER BY id DESC LIMIT 1",
  );
  if (!fila) return null;
  const id = Number(fila.id);
  const cuenta = await db.get<{ n: number }>(
    "SELECT COUNT(*)::int AS n FROM lotes WHERE proceso_id = ?",
    id,
  );
  return { id, entradas: Number(cuenta?.n ?? 0) };
}

