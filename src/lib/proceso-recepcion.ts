export async function reiniciarCarga(db: Db): Promise<Resultado<number>> {
  await asegurarProceso(db);
  return db.transaction(async (tx) => {
    const abierto = await tx.get<{ id: number }>(
      "SELECT id FROM procesos_recepcion WHERE estado = 'abierta' ORDER BY id DESC LIMIT 1 FOR UPDATE",
    );
    if (!abierto) return { ok: false, error: "No hay un proceso de recepción en curso." };
    const id = Number(abierto.id);
    const filas = await tx.all<{ tag: string; kg_despachados: number; kg_consumidos: number; estado: string }>(
      "SELECT tag, kg_despachados, kg_consumidos, estado FROM lotes WHERE proceso_id = ? FOR UPDATE",
      id,
    );
    const usado = filas.find(
      (fila) => Number(fila.kg_despachados) > 0 || Number(fila.kg_consumidos) > 0 || fila.estado !== "RECIBIDO",
    );
    if (usado) {
      return { ok: false, error: `No se puede reiniciar porque el TAG ${usado.tag} ya se usó.` };
    }
    for (const fila of filas) {
      const minis = await tx.get<{ n: number }>("SELECT COUNT(*)::int AS n FROM minilotes WHERE tag = ?", fila.tag);
      if (Number(minis?.n ?? 0) > 0) {
        return { ok: false, error: `No se puede reiniciar porque el TAG ${fila.tag} ya tiene retiros.` };
      }
    }
    for (const fila of filas) {
      await tx.run("DELETE FROM movimientos WHERE tag = ?", fila.tag);
      await tx.run("DELETE FROM lotes WHERE tag = ?", fila.tag);
    }
    return { ok: true, value: filas.length };
  });
}

async function quitarEtiqueta(
  tx: Db,
  procesoId: number,
  tag: string,
): Promise<{ ok: true } | { ok: false; error: string }> {
  const fila = await tx.get<{ tag: string; kg_despachados: number; kg_consumidos: number; estado: string; impresa_en: string }>(
    "SELECT tag, kg_despachados, kg_consumidos, estado, impresa_en FROM lotes WHERE tag = ? AND proceso_id = ? FOR UPDATE",
    tag,
    procesoId,
  );
  if (!fila) return { ok: false, error: `La etiqueta del TAG ${tag} no pertenece a este proceso.` };
  if (fila.impresa_en !== "") return { ok: false, error: `El TAG ${tag} ya se envió a imprimir.` };
  if (Number(fila.kg_despachados) > 0 || Number(fila.kg_consumidos) > 0 || fila.estado !== "RECIBIDO") {
    return { ok: false, error: `No se puede eliminar el TAG ${tag} porque ya se usó.` };
  }
  const minis = await tx.get<{ n: number }>("SELECT COUNT(*)::int AS n FROM minilotes WHERE tag = ?", tag);
  if (Number(minis?.n ?? 0) > 0) {
    return { ok: false, error: `No se puede eliminar el TAG ${tag} porque ya tiene retiros.` };
  }
  return { ok: true };
}

export async function eliminarEntradaEnCurso(db: Db, tag: string): Promise<Resultado> {
  await asegurarProceso(db);
  const limpio = tag.trim();
  if (!limpio) return { ok: false, error: "No se pudo identificar la etiqueta." };
  return db.transaction(async (tx) => {
    const abierto = await tx.get<{ id: number }>(
      "SELECT id FROM procesos_recepcion WHERE estado = 'abierta' ORDER BY id DESC LIMIT 1 FOR UPDATE",
    );
    if (!abierto) return { ok: false, error: "No hay un proceso de recepción en curso." };
    const revisada = await quitarEtiqueta(tx, Number(abierto.id), limpio);
    if (!revisada.ok) return revisada;
    await tx.run("DELETE FROM movimientos WHERE tag = ?", limpio);
    await tx.run("DELETE FROM lotes WHERE tag = ?", limpio);
    return { ok: true, value: undefined };
  });
}

export async function eliminarEntradaPorImprimir(db: Db, procesoId: number, tag: string): Promise<Resultado> {
  const resultado = await eliminarEntradasPorImprimir(db, procesoId, [tag]);
  if (!resultado.ok) return resultado;
  return { ok: true, value: undefined };
}

export async function eliminarEntradasPorImprimir(
  db: Db,
  procesoId: number,
  tags: string[] | "todas",
): Promise<Resultado<number>> {
  await asegurarProceso(db);
  if (!Number.isInteger(procesoId) || procesoId <= 0) {
    return { ok: false, error: "No se pudo identificar el proceso." };
  }
  return db.transaction(async (tx) => {
    const proceso = await tx.get<{ estado: string }>("SELECT estado FROM procesos_recepcion WHERE id = ?", procesoId);
    if (!proceso || proceso.estado !== "cerrada") {
      return { ok: false, error: "Esas etiquetas ya no están en un proceso listo para imprimir." };
    }
    const pedidas =
      tags === "todas"
        ? (await tx.all<{ tag: string }>(
            "SELECT tag FROM lotes WHERE proceso_id = ? AND impresa_en = '' ORDER BY creado_en, tag",
            procesoId,
          )).map((fila) => fila.tag)
        : [...new Set(tags.map((tag) => tag.trim()).filter(Boolean))];
    if (pedidas.length === 0) {
      return { ok: false, error: tags === "todas" ? "No hay etiquetas para eliminar." : "Selecciona al menos una etiqueta." };
    }
    for (const tag of pedidas) {
      const revisada = await quitarEtiqueta(tx, procesoId, tag);
      if (!revisada.ok) return revisada;
    }
    for (const tag of pedidas) {
      await tx.run("DELETE FROM movimientos WHERE tag = ?", tag);
      await tx.run("DELETE FROM lotes WHERE tag = ?", tag);
    }
    return { ok: true, value: pedidas.length };
  });
}

export async function guardarEtiquetasDelProceso(db: Db, procesoId: number): Promise<Resultado<number>> {
  await asegurarProceso(db);
  if (!Number.isInteger(procesoId) || procesoId <= 0) {
    return { ok: false, error: "No se pudo identificar el proceso." };
  }
  return db.transaction(async (tx) => {
    const proceso = await tx.get<{ estado: string }>(
      "SELECT estado FROM procesos_recepcion WHERE id = ? FOR UPDATE",
      procesoId,
    );
    if (!proceso || proceso.estado !== "cerrada") {
      return { ok: false, error: "Ese proceso no está listo para guardar." };
    }
    const filas = await tx.all<{ tag: string }>(
      "SELECT tag FROM lotes WHERE proceso_id = ? AND impresa_en = '' ORDER BY creado_en, tag FOR UPDATE",
      procesoId,
    );
    if (filas.length === 0) return { ok: false, error: "No hay etiquetas para guardar." };
    for (const fila of filas) {
      await tx.run("UPDATE lotes SET impresa_en = 'guardada' WHERE tag = ?", fila.tag);
    }
    return { ok: true, value: filas.length };
  });
}

export async function procesosPorImprimir(db: Db): Promise<ProcesoPorImprimir[]> {
  await asegurarProceso(db);
  const filas = await db.all<{ id: number; n: number }>(`
    SELECT p.id, COUNT(l.tag)::int AS n
    FROM procesos_recepcion p
    JOIN lotes l ON l.proceso_id = p.id AND l.impresa_en = ''
    WHERE p.estado = 'cerrada'
    GROUP BY p.id
    ORDER BY p.id DESC
  `);
  return filas.map((fila) => ({ id: Number(fila.id), entradas: Number(fila.n) }));
}
