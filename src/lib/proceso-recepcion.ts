export async function terminarProceso(db: Db): Promise<Resultado<{ id: number; entradas: number }>> {
  await asegurarProceso(db);
  const ahora = new Date().toISOString();
  return db.transaction(async (tx) => {
    const abierto = await tx.get<{ id: number }>(
      "SELECT id FROM procesos_recepcion WHERE estado = 'abierta' ORDER BY id DESC LIMIT 1 FOR UPDATE",
    );
    if (!abierto) return { ok: false, error: "No hay un proceso de recepción en curso." };
    const id = Number(abierto.id);
    const cuenta = await tx.get<{ n: number }>("SELECT COUNT(*)::int AS n FROM lotes WHERE proceso_id = ?", id);
    await tx.run("UPDATE procesos_recepcion SET estado = 'cerrada', cerrada_en = ? WHERE id = ?", ahora, id);
    return { ok: true, value: { id, entradas: Number(cuenta?.n ?? 0) } };
  });
}

